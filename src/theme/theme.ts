export function themeByName(name: string | undefined): Theme {
  return themes.find((t) => t.name === name) ?? themes[0]!
}

/** OpenTUI's "no fill": the cell keeps the terminal's own background. Set it explicitly: the reconciler never clears a dropped prop. */
export const CLEAR = "transparent"

/** The fills of the main surfaces: the theme's, or `CLEAR` when the terminal background should show through. Popups, the scrim, the drawer (it floats over the text) and code blocks never use this. */
export function surface(t: Theme, transparent: boolean) {
  return {
    main: transparent ? CLEAR : t.background,
    side: transparent ? CLEAR : mix(t.background, t.backgroundElement, 0.6),
  }
}

function luminance(hex: string): number {
  const c = [1, 3, 5].map((i) => {
    const v = parseInt(hex.slice(i, i + 2), 16) / 255
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!
}

/** WCAG contrast ratio of two `#rrggbb` colors. */
export function contrast(a: string, b: string): number {
  const [la, lb] = [luminance(a), luminance(b)]
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05)
}

/** Readable foreground (dark or light) for text drawn on `bg`, by WCAG contrast ratio. */
export function contrastOn(bg: string): string {
  return contrast(bg, "#1a1a1a") >= contrast(bg, "#f0f0f0") ? "#1a1a1a" : "#f0f0f0"
}

/** `a` blended `k` of the way towards `b` (both `#rrggbb`). */
export function mix(a: string, b: string, k: number): string {
  const ch = (hex: string, i: number) => parseInt(hex.slice(i, i + 2), 16)
  return (
    "#" +
    [1, 3, 5]
      .map((i) =>
        Math.round(ch(a, i) + (ch(b, i) - ch(a, i)) * k)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  )
}
